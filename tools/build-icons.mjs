// Builds site/js/icons.js: only the Lucide icons the site actually uses.
// Run after adding a new <i data-lucide="..."> anywhere in site/:
//   node tools/build-icons.mjs
// Source: tools/lucide.min.js (full Lucide library, not published).
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const site = path.join(root, "site");

const ctx = { globalThis: {} };
ctx.self = ctx.globalThis;
vm.runInNewContext(fs.readFileSync(path.join(root, "tools/lucide.min.js"), "utf8"), ctx);
const lucide = ctx.globalThis.lucide;

const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(html|js)$/.test(e.name) && e.name !== "icons.js") files.push(p);
  }
})(site);

const names = new Set();
for (const f of files) for (const m of fs.readFileSync(f, "utf8").matchAll(/data-lucide=\\?["']([a-z0-9-]+)/g)) names.add(m[1]);

const pascal = (n) => n.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const icons = {};
const missing = [];
for (const n of [...names].sort()) {
  const node = lucide.icons[pascal(n)];
  if (node) icons[n] = JSON.parse(JSON.stringify(node));
  else missing.push(n);
}
if (missing.length) { console.error("Unknown icon names:", missing.join(", ")); process.exit(1); }

const out = `/* Generated by tools/build-icons.mjs from Lucide ${"v0.544.0"} (ISC license). Do not edit.
   ${Object.keys(icons).length} icons. Turns <i data-lucide="name"> into inline SVG, like lucide.createIcons(). */
(function () {
  var ICONS = ${JSON.stringify(icons)};
  var NS = "http://www.w3.org/2000/svg";
  var BASE = { xmlns: NS, width: 24, height: 24, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor", "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round" };
  function el(tag, attrs) {
    var e = document.createElementNS(NS, tag);
    for (var k in attrs) e.setAttribute(k, attrs[k]);
    return e;
  }
  function createIcons() {
    var list = document.querySelectorAll("[data-lucide]");
    for (var i = 0; i < list.length; i++) {
      var src = list[i];
      if (src.namespaceURI === NS) continue;
      var name = src.getAttribute("data-lucide");
      var node = ICONS[name];
      if (!node) continue;
      var svg = el("svg", BASE);
      for (var a = 0; a < src.attributes.length; a++) {
        var at = src.attributes[a];
        if (at.name !== "class") svg.setAttribute(at.name, at.value);
      }
      svg.setAttribute("class", ["lucide", "lucide-" + name, src.getAttribute("class") || ""].join(" ").trim());
      if (!src.hasAttribute("aria-label") && !src.hasAttribute("aria-hidden")) svg.setAttribute("aria-hidden", "true");
      for (var c = 0; c < node.length; c++) svg.appendChild(el(node[c][0], node[c][1]));
      src.parentNode.replaceChild(svg, src);
    }
  }
  window.lucide = { createIcons: createIcons };
})();
`;
fs.writeFileSync(path.join(site, "js/icons.js"), out);
console.log(`site/js/icons.js: ${Object.keys(icons).length} icons, ${out.length} bytes`);
